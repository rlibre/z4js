// closed list: a name outside of it is a programming error
export const SECURITY_EVENTS = [
	"auth.login.ok",
	"auth.login.failed",
	"auth.unauthorized",
	"auth.forbidden",
	"auth.stepup.required",
	"auth.stepup.ok",
	"auth.stepup.failed",
	"auth.session.revoked",
	"auth.ticket.refused",
	"auth.rights.changed"
] as const;

export type SecurityEvent = ( typeof SECURITY_EVENTS )[number];

export interface SecurityLogOptions {
	file?: string;			// own destination, same rules as the logger
	mode?: number;
	extraEvents?: readonly string[];	// events added by the application
}

// same line format, fixed level "SEC", never filtered by level and never dropped
export class SecurityLog {
	private readonly sink: Sink;
	private readonly allowed: ReadonlySet<string>;

	constructor( options: SecurityLogOptions = {} ) {
		const extra = options.extraEvents ?? [];
		extra.forEach( checkEvent );

		this.allowed = new Set<string>( [...SECURITY_EVENTS, ...extra] );
		this.sink = new Sink( options.file ?? null, options.mode ?? 0o600 );
	}

	log( event: string, data?: Record<string, unknown>, requestId?: string ) {
		if( !this.allowed.has( event ) ) {
			throw new Error( "security log: unknown event" );
		}

		if( requestId !== undefined ) {
			checkRequestId( requestId );
		}

		this.sink.write( formatLine( "SEC", requestId, event, data ), {
			stderr: false,
			droppable: false,
			sync: false
		} );
	}

	close( ) {
		this.sink.close( );
	}
}
