// Logger and security log.
//
// Line format (one event per line):
//
//   <ISO date time UTC> <LEVEL> <request id or -> <event> [<json data>]
//
// Everything before the JSON part is produced by z4js itself: the event name is
// checked against a strict pattern (or a closed list for security events) and the
// request id is generated by z4js. Anything coming from a client goes only in the
// JSON part, where newlines are escaped and strings are truncated, so a client can
// never forge a log line.
//
// Destination: null = standard output (standard error from "error" up),
// otherwise a file path where ${date} (UTC, YYYY-MM-DD) is the only accepted token.

import { appendFileSync, createWriteStream, statSync, type WriteStream } from "node:fs";
import { dirname } from "node:path";

// from the most to the least verbose: the type and the ranks derive from this list
export const LOG_LEVELS = ["debug", "info", "warn", "error", "fatal"] as const;

export type LogLevel = ( typeof LOG_LEVELS )[number];

const RANK = Object.fromEntries( LOG_LEVELS.map( ( level, i ) => [level, i] ) ) as Record<LogLevel, number>;

// longest string value kept in the JSON part (anything longer is cut)
const MAX_STRING = 256;

// above this many pending bytes, low level lines are dropped (and counted)
const MAX_PENDING_BYTES = 1024 * 1024;

const EVENT_RE = /^[a-z][a-z0-9._-]{0,63}$/;
const REQUEST_ID_RE = /^[A-Za-z0-9_-]{1,64}$/;
const DATE_TOKEN = "${date}";

// ---------------------------------------------------------------------------

function checkEvent( event: string ) {
	// a bad event name is a programming error, not a runtime condition
	if( !EVENT_RE.test( event ) ) {
		throw new Error( "log: invalid event name" );
	}
}

function checkRequestId( id: string ) {
	if( !REQUEST_ID_RE.test( id ) ) {
		throw new Error( "log: invalid request id" );
	}
}

function utcDate( ) {
	return new Date( ).toISOString( ).slice( 0, 10 );
}

function safeJson( data: Record<string, unknown>, withStack: boolean ): string {
	const replacer = ( _key: string, value: unknown ) => {
		if( typeof value === "string" ) {
			return value.length > MAX_STRING ? value.slice( 0, MAX_STRING ) + "…" : value;
		}

		if( typeof value === "bigint" ) {
			return value.toString( );
		}

		if( value instanceof Error ) {
			const err: Record<string, unknown> = { name: value.name, message: value.message };
			if( withStack && value.stack ) {
				err.stack = value.stack;
			}
			return err;
		}

		return value;
	};

	let json: string;
	try {
		json = JSON.stringify( data, replacer );
	}
	catch {
		// circular structure or similar: never let logging throw
		json = '{"log":"unserializable"}';
	}

	// JSON.stringify leaves these two as they are, but some tools treat them as line breaks
	return json.replaceAll( "\u2028", "\\u2028" ).replaceAll( "\u2029", "\\u2029" );
}

function formatLine(
	level: string,
	requestId: string,
	event: string,
	data?: Record<string, unknown>,
	withStack = false
) {
	let line = `${new Date( ).toISOString( )} ${level} ${requestId ?? "-"} ${event}`;
	if( data !== undefined ) {
		line += " " + safeJson( data, withStack );
	}

	return line + "\n";
}

function reportFileFailure( ) {
	process.stderr.write( formatLine( "ERROR", undefined, "log.file.failed" ) );
}

// ---------------------------------------------------------------------------

interface WriteOptions {
	stderr: boolean;		// standard error instead of standard output (no file)
	droppable: boolean;		// may be dropped when the file is too slow
	sync: boolean;			// written synchronously (fatal errors: the process may exit right after)
}

// owns the destination: standard streams, or an append-only file following ${date}
class Sink {
	private stream: WriteStream = null;
	private streamPath = "";
	private dropped = 0;

	constructor( private readonly template: string, private readonly mode: number ) {
		if( template === null ) {
			return;
		}

		if( template.replaceAll( DATE_TOKEN, "" ).includes( "${" ) ) {
			throw new Error( "log file: only ${date} is accepted in the path" );
		}

		const dir = dirname( template );
		if( dir.includes( DATE_TOKEN ) ) {
			throw new Error( "log file: ${date} is accepted in the file name only" );
		}

		// the folder must already exist: it is created (or not) at init, never here
		if( !statSync( dir ).isDirectory( ) ) {
			throw new Error( "log file: the parent is not a folder" );
		}
	}

	write( line: string, opts: WriteOptions ) {
		if( this.template === null ) {
			( opts.stderr ? process.stderr : process.stdout ).write( line );
			return;
		}

		const path = this.template.replaceAll( DATE_TOKEN, utcDate( ) );

		try {
			if( opts.sync ) {
				appendFileSync( path, line, { mode: this.mode } );
				return;
			}

			const stream = this.open( path );

			if( opts.droppable && stream.writableLength > MAX_PENDING_BYTES ) {
				this.dropped++;
				return;
			}

			if( this.dropped > 0 ) {
				stream.write( formatLine( "WARN", undefined, "log.dropped", { count: this.dropped } ) );
				this.dropped = 0;
			}

			stream.write( line );
		}
		catch {
			this.fallback( line );
		}
	}

	close( ) {
		this.stream?.end( );
		this.stream = null;
	}

	// a line is never lost silently: if the file fails, it goes to standard error
	private fallback( line: string ) {
		reportFileFailure( );
		process.stderr.write( line );
	}

	private open( path: string ): WriteStream {
		if( this.stream && this.streamPath === path ) {
			return this.stream;
		}

		// date changed (or first write): move to the new file
		this.stream?.end( );

		const stream = createWriteStream( path, { flags: "a", mode: this.mode } );
		stream.on( "error", ( ) => {
			reportFileFailure( );
			if( this.stream === stream ) {
				this.stream = null;
			}
		} );

		this.stream = stream;
		this.streamPath = path;
		return stream;
	}
}

