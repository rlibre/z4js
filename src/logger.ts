export interface LoggerOptions {
	level: LogLevel;				// minimal level written
	file?: string;			// null or absent = standard output/error
	mode?: number;					// file permissions, owner only by default
}

interface Core {
	sink: Sink;
	min: number;
}

// the application log: one line per event, filtered by level, written to the
// standard output or to a file. child( ) gives the logger of one request
export class Logger {
	private constructor( private readonly core: Core, private readonly requestId?: string ) {
	}

	static create( options: LoggerOptions ): Logger {
		return new Logger( {
			sink: new Sink( options.file ?? null, options.mode ?? 0o600 ),
			min: RANK[options.level]
		} );
	}

	// same destination, every line carries the given request id (generated by z4js)
	child( requestId: string ): Logger {
		checkRequestId( requestId );
		return new Logger( this.core, requestId );
	}

	debug( event: string, data?: Record<string, unknown> ) { this.log( "debug", event, data ); }
	info( event: string, data?: Record<string, unknown> ) { this.log( "info", event, data ); }
	warn( event: string, data?: Record<string, unknown> ) { this.log( "warn", event, data ); }
	error( event: string, data?: Record<string, unknown> ) { this.log( "error", event, data ); }
	fatal( event: string, data?: Record<string, unknown> ) {
		this.log( "fatal", event, data );

		// debug level: stop in the debugger, the line is already written (sync).
		// "debugger" does nothing when no debugger is attached
		if( this.core.min === RANK.debug ) {
			debugger;
		}
	}

	close( ) {
		this.core.sink.close( );
	}

	private log( level: LogLevel, event: string, data?: Record<string, unknown> ) {
		checkEvent( event );

		const rank = RANK[level];
		if( rank < this.core.min ) {
			return;
		}

		const line = formatLine( level.toUpperCase( ), this.requestId, event, data, rank >= RANK.error );

		this.core.sink.write( line, {
			stderr: rank >= RANK.error,
			droppable: rank < RANK.warn,
			sync: level === "fatal"
		} );
	}
}

